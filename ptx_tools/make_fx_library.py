#!/usr/bin/env python3
"""make_fx_library.py <project.rpp> [...] — собирает reaper_fx_library.py из проектов, сохранённых самим Reaper.

В проекте плагины добавлены в Reaper вручную (настройки по умолчанию); блок <VST ...> с его состоянием берётся целиком и
потом подставляется в цепочки FX при конвертации Pro Tools -> Reaper. Ключ — идентификатор плагина (без закрывающей «}»).
"""
import sys
import os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rpp  # noqa: E402

lib = {}
if os.path.exists('reaper_fx_library.py'):
    exec(open('reaper_fx_library.py').read(), globals())
    lib = dict(LIBRARY)                                   # noqa: F821
for path in sys.argv[1:]:
    lines = open(path, encoding='utf-8', errors='replace').read().splitlines()
    i = 0
    while i < len(lines):
        t = lines[i].strip()
        if t.startswith('<VST '):
            tok = rpp.tokenize(t[1:])
            depth, j = 1, i + 1
            block = [t]
            while j < len(lines) and depth:
                u = lines[j].strip()
                if u.startswith('<'):
                    depth += 1
                elif u == '>':
                    depth -= 1
                block.append(u)
                j += 1
            if j < len(lines) and lines[j].strip().startswith('PRESETNAME'):
                block.append(lines[j].strip())
                j += 1
            if len(tok) >= 6:
                lib[tok[5].rstrip('}')] = block
            i = j
        else:
            i += 1
with open('reaper_fx_library.py', 'w') as f:
    f.write('# generated by make_fx_library.py — do not edit\nLIBRARY = {\n')
    for k, v in sorted(lib.items()):
        f.write(f'    {k!r}: {v!r},\n')
    f.write('}\n')
print(len(lib), 'plugins')
