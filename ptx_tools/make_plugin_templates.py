#!/usr/bin/env python3
"""Генерирует ptx_templates_plugins.py: готовые вставки плагинов (слот инсерта 0x2616) из сессий, сохранённых Pro Tools.

make_plugin_templates.py <session.ptx> [...] — берёт у каждой дорожки каждый занятый слот 0x2616 (настройки по умолчанию, как их
записал Pro Tools при вставке плагина вручную), ключ — (производитель, продукт, вариант) FourCC; дополняет существующий файл.
"""
import os
import re
import sys
import zlib

MAX_SLOT = 400000                                              # байт: больше — состояние с данными сессии, не шаблон

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ptx_model import PTX, Block  # noqa: E402
import ptx_to_reaper as R  # noqa: E402
import ptx_trackstate as TS  # noqa: E402
import ptx_plugins as PL  # noqa: E402

def cat_entry(p, key, blk=None):
    """Запись плагина в каталоге сессии 0x1018 (с bundle id) — байты блока целиком."""
    import struct
    r = [x for x in p.roots if isinstance(x, Block) and x.ctype == 0x1018][0]
    if blk is not None and TS.kids(blk, 0x2615):                # точная запись — по номеру, который записал сам Pro Tools
        idx = struct.unpack_from('<H', TS.own_bytes(TS.kids(blk, 0x2615)[0]), 2)[0]
        ents = TS.kids(r, 0x1017)
        if idx < len(ents):
            return R.flat([ents[idx]])
    for e in TS.kids(r, 0x1017):
        o = TS.own_bytes(e)
        n = struct.unpack_from('<I', o, 3)[0]
        f = o[7 + n:7 + n + 12]
        if tuple(bytes(f[i:i + 4][::-1]) for i in (0, 4, 8)) == key:
            return R.flat([e])
    for e in TS.kids(r, 0x1017):                              # запасной вариант: тот же производитель и продукт (другой вариант каналов)
        o = TS.own_bytes(e)
        n = struct.unpack_from('<I', o, 3)[0]
        f = o[7 + n:7 + n + 12]
        if tuple(bytes(f[i:i + 4][::-1]) for i in (0, 4)) == key[:2]:
            return R.flat([e])
    return None


lib = {}
if os.path.exists('ptx_templates_plugins.py'):
    exec(open('ptx_templates_plugins.py').read(), globals())
    lib = dict(SLOTS)                                                # noqa: F821
for path in sys.argv[1:]:
    p = PTX(open(path, 'rb').read())
    cat = PL.read_catalog(p)
    chans = {}
    for i, st in enumerate(TS.read_states(p)):
        chans[i] = {1: 'mono', 2: 'stereo', 6: '5.1'}.get(st.get('channels'), None)
    for ti, (tb, pls) in enumerate(zip(TS.track_blocks(p), PL.read_plugins(p))):
        if not pls:
            continue
        d = TS.kids(TS.kids(tb, 0x261b)[0], 0x2627)[0]
        slots = [x for x in d.items if isinstance(x, Block)]
        for pl in pls:
            blk = slots[pl['slot']]
            if not TS.kids(blk, 0x2615):                          # плагин без записи в каталоге сессии (не загружен / отсутствует): не годится
                continue
            flat = R.flat([blk])
            if pl['bypass']:                                          # шаблон хранится в активном состоянии (байт bypass — в конце блока)
                from ptx_build import clone
                c = clone(flat)
                TS.own_patch(c, 2, b'\x00')
                flat = R.flat([c])
            cat = cat_entry(p, pl['key'], blk)
            if cat is None or len(flat) > MAX_SLOT or '?' in pl['name'] or re.fullmatch(r'.{4}/.{4}/.{4}', pl['name']):
                continue                                          # нет записи в каталоге / огромное состояние (данные замеров) / имя не определено
            lib.setdefault(pl['key'] + (chans.get(ti) or pl['format'],), {'name': pl['name'], 'format': chans.get(ti) or pl['format'], 'slot': zlib.compress(flat, 9), 'catalog': cat})
with open('ptx_templates_plugins.py', 'w') as f:
    f.write('# generated by make_plugin_templates.py — do not edit\nSLOTS = {\n')
    for k, v in sorted(lib.items()):
        f.write(f'    {k!r}: {v!r},\n')
    f.write('}\n')
print(len(lib), 'plugins:', [v['name'] + ' (' + v['format'] + ')' for v in lib.values()])
