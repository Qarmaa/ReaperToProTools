#!/usr/bin/env python3
"""make_plugin_ids.py — таблица идентичностей установленных AAX-плагинов (имя, производитель, продукт, ID по форматам) -> ptx_plugin_ids.py.

Разработческий инструмент: спрашивает у каждого .aaxplugin его описание через DigiShell (Avid AAX Developer Tools, в приложение
не входят). Готовая таблица — обычные данные (имена и FourCC), они нужны, чтобы создать в .ptx слот плагина, которого нет среди
встроенных шаблонов (см. ptx_slot_gen.py).

    DIGISHELL=/path/to/DigiShell/CommandLineTools make_plugin_ids.py [bundle ...]   (без аргументов — все из /Library/.../Plug-Ins)
Результат дописывается к существующей ptx_plugin_ids.py (ключ — имя из описания плагина).
"""
import concurrent.futures
import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DSH = os.environ.get('DIGISHELL', '')                       # папка CommandLineTools из AAX Developer Tools (Avid; в проект не входит)
PLUGDIR = '/Library/Application Support/Avid/Audio/Plug-Ins'
STEM = {1: 'mono', 0x10002: 'stereo', 0x20003: 'LCR', 0x30004: 'LCRS', 0x40004: 'quad', 0x50005: '5.0', 0x60006: '5.1'}
MAX_EFFECTS = 6


def describe(bundle):
    steps = ['load_dish aaxh', 'aaxh.init', f'aaxh.loadpi "{bundle}"', 'aaxh.listeffects']
    steps += [f'aaxh.getdescription {{plugin: 0, effect: {i}}}' for i in range(MAX_EFFECTS)]
    body = ''.join(f"printf '%s\\n' '{c}'; sleep {4 if 'loadpi' in c else 1.5}; " for c in steps)
    script = f'cd "{DSH}"; ({body} printf "exit\\n") | perl -e \'alarm 90; exec @ARGV\' ./dsh 2>&1'
    r = subprocess.run(['bash', '-c', script], capture_output=True, timeout=120)
    return r.stdout.decode('utf-8', 'replace')


def fourcc(s):
    m = re.search(r"'(.{4})'", s)
    return m.group(1) if m else None


def parse(text, bundle):
    res = []
    eids = re.findall(r'effectID:\s*(\S+)', text)
    for d in re.findall(r'<plugin_descriptor>(.*?)</plugin_descriptor>', text, re.S):
        name = re.search(r'<name>\s*(.*?)\s*</name>', d, re.S)
        props = {}
        for comp in re.split(r'<component_descriptor>', d):
            for k, v in re.findall(r'<key>\s*(\S+)\s*</key>\s*<val_formatted>\s*(.*?)\s*</val_formatted>', comp, re.S):
                props.setdefault(k, []).append(v)
        mfr = fourcc((props.get('AAX_eProperty_ManufacturerID') or [''])[0])
        prod = fourcc((props.get('AAX_eProperty_ProductID') or [''])[0])
        plugs = {}
        for comp in re.split(r'<component_descriptor>', d)[1:]:
            nat = re.search(r'<key>\s*AAX_eProperty_PlugInID_Native\s*</key>\s*<val_formatted>\s*(.*?)\s*</val_formatted>', comp, re.S)
            ins = re.search(r'<key>\s*AAX_eProperty_InputStemFormat\s*</key>\s*<val_literal>\s*(\d+)', comp, re.S)
            outs = re.search(r'<key>\s*AAX_eProperty_OutputStemFormat\s*</key>\s*<val_literal>\s*(\d+)', comp, re.S)
            if nat and ins and outs and ins.group(1) == outs.group(1) and int(ins.group(1)) in STEM:
                f = fourcc(nat.group(1))
                if f:
                    plugs.setdefault(STEM[int(ins.group(1))], f)
        if name and mfr and prod:
            parts = [x.strip() for x in name.group(1).split('\n') if x.strip()]
            res.append({'name': parts[0], 'aliases': parts[1:], 'mfr': mfr, 'prod': prod, 'plugs': plugs, 'bundle': os.path.basename(bundle),
                        'eid': eids[len(res)] if len(eids) > len(res) else ''})
    return res


def main():
    bundles = sys.argv[1:] or sorted(glob.glob(PLUGDIR + '/**/*.aaxplugin', recursive=True))
    bundles = [b for b in bundles if 'WaveShell' not in b and 'SoundGrid' not in b]
    out = {}
    try:
        ns = {}
        exec(open(os.path.join(HERE, 'ptx_plugin_ids.py')).read(), ns)
        out = dict(ns['IDS'])
    except OSError:
        pass
    with concurrent.futures.ThreadPoolExecutor(4) as ex:
        for b, text in zip(bundles, ex.map(describe, bundles)):
            got = parse(text, b)
            print(os.path.basename(b), [(g['name'], g['mfr'], g['prod'], sorted(g['plugs'])) for g in got], flush=True)
            for g in got:
                out[g['name']] = {k: g[k] for k in ('mfr', 'prod', 'plugs', 'bundle', 'eid', 'aliases')}
    with open(os.path.join(HERE, 'ptx_plugin_ids.py'), 'w') as f:
        f.write('# generated by make_plugin_ids.py — do not edit\nIDS = {\n')
        for k, v in sorted(out.items()):
            f.write(f'    {k!r}: {v!r},\n')
        f.write('}\n')
    print(len(out), 'plugins')


if __name__ == '__main__':
    main()
