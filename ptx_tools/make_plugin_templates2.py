#!/usr/bin/env python3
"""make_plugin_templates2.py — вторая встроенная библиотека шаблонов плагинов (ptx_templates_plugins2.py): слоты, которые СОЗДАЛ САМ Pro Tools.

Цикл (см. pt_cycle.sh): сессия со слотами по таблице идентичностей (ptx_slot_gen, состояние пустое) -> Pro Tools открывает и сохраняет ->
в сохранённой копии у каждого установленного плагина настоящее состояние по умолчанию. Эти слоты и забираем (их состояние нужно, чтобы
потом подставлять настройки из Reaper). Плагины, которые Pro Tools не смог загрузить (состояние пустое), не берём.

    make_plugin_templates2.py [--input synthesized.ptx] <saved_by_pt.ptx> [...]
  --input: исходная сессия со слотами по таблице; плагины, которых Pro Tools после открытия не оставил (MIDI/инструменты, не годятся
  для инсерта аудио), их тройки FourCC попадают в NOT_INSERTABLE и больше не создаются.
"""
import os
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ptx_plugin_learn as L  # noqa: E402
import ptx_trackstate as TS  # noqa: E402
import ptx_build as B  # noqa: E402

MIN_STATE = 66 + 8


def state_len(v):
    try:
        blk = B.clone(zlib.decompress(v['slot']))
        return len(TS.own_bytes(TS.kids(TS.kids(TS.kids(blk, 0x2615)[0], 0x2613)[0], 0x1038)[0]))
    except (IndexError, KeyError):
        return 0


def not_insertable(src, saved):
    from ptx_model import PTX
    import ptx_plugins as PL

    def slots(f):
        return {(ti, x['slot']): x['key'] for ti, tr in enumerate(PL.read_plugins(PTX(open(f, 'rb').read()))) for x in tr}
    a, b = slots(src), slots(saved)
    return sorted({kk for k, kk in a.items() if k not in b})


def main():
    import tempfile
    args = sys.argv[1:]
    src = None
    if '--input' in args:
        i = args.index('--input')
        src = args[i + 1]
        del args[i:i + 2]
    sys.argv = [sys.argv[0]] + args
    tmp = tempfile.mkdtemp()
    L.USER_DIR, L.USER_FILE = tmp, os.path.join(tmp, 'x.dat')
    L.learn(sys.argv[1:])
    lib = L.load_user()
    keep = {k: v for k, v in lib.items() if state_len(v) >= MIN_STATE}
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ptx_templates_plugins2.py')
    with open(path, 'w') as f:
        f.write('# generated by make_plugin_templates2.py (слоты, сохранённые Pro Tools) — do not edit\nSLOTS2 = {\n')
        for k, v in sorted(keep.items()):
            f.write(f'    {k!r}: {v!r},\n')
        f.write('}\n')
        if src:
            f.write('NOT_INSERTABLE = %r\n' % (not_insertable(src, args[0]),))
    print(len(lib), 'learned,', len(keep), 'kept ->', path, os.path.getsize(path), 'bytes')


if __name__ == '__main__':
    main()
