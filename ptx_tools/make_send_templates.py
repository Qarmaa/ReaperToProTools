#!/usr/bin/env python3
"""Генерирует ptx_templates_sends.py: блоки шин и sends из эталона lab/sends/snd2.ptx (Pro Tools 26.4).

  BUS_ENTRY  : запись шины в I/O Setup (0x1021 в 0x1022; в обеих половинах списка)  — mono Bus1 / stereo Bus2
  REC2602    : запись шины в списке 0x2603>0x2602
  PATHOBJ    : объект пути 0x260e внутри слота send (и в списке 0x4856 дорожки)
  E485E      : блоки 0x485e в 0x4856 (основной выход / send)
"""
import sys
sys.path.insert(0, '.')
from ptx_model import PTX, Block
import ptx_to_reaper as R, ptx_trackstate as TS

p = PTX(open('lab/sends/snd2.ptx', 'rb').read())


def flat(b):
    return R.flat([b])


def _id8(e):
    o = TS.own_bytes(e)
    k = o.index(b'*\x00\x00\x00') + 4
    return o[k:k + 8]


r1022 = R.root(p, 0x1022)
ents = [k for k in r1022.items if isinstance(k, Block)]
half = len(ents) // 2
by_name = {}
for e in ents[:half]:
    o = TS.own_bytes(e)
    import struct
    n = struct.unpack_from('<I', o, 4)[0]
    by_name[o[8:8 + n].decode()] = e
r2603 = R.root(p, 0x2603)
recs = {}
for e in R.kids(r2603, 0x2602):
    o = TS.own_bytes(e)
    n = struct.unpack_from('<I', o, 4)[0]
    recs[o[8:8 + n].decode()] = e
names = [n for n, *_ in TS.aggregate_names(p)]
tbl = TS.track_blocks(p)
a = tbl[names.index('A')]
b261b = R.kids(a, 0x261b)[0]
slots = R.kids(b261b, 0x260d)
po = {'mono': flat(R.kids(slots[1], 0x260e)[0]), 'stereo': flat(R.kids(slots[2], 0x260e)[0])}
b4856 = R.kids(b261b, 0x4856)[0]
e485 = R.kids(b4856, 0x485e)
p1 = PTX(open('lab/sends/snd1.ptx', 'rb').read())
a1 = TS.track_blocks(p1)[[n for n, *_ in TS.aggregate_names(p1)].index('A')]
# слоты в «нормализованном» виде — как их пересохраняет сам Pro Tools (иначе он при загрузке сбрасывает pre-fader в post)
pb2 = PTX(open('lab/sends/out/b2/b2.ptx', 'rb').read())                 # PT-пересохранение: A -> Bus1 (mono -> mono)
slot_mono_mono = flat(R.kids(R.kids(TS.track_blocks(pb2)[[n for n, *_ in TS.aggregate_names(pb2)].index('A')], 0x261b)[0], 0x260d)[1])
pe3 = PTX(open('lab/sends/out/o6/env3/env3.ptx', 'rb').read())          # PT-пересохранение: Mono1 -> Reverb (mono -> stereo)
slot_mono_stereo = flat(R.kids(R.kids(TS.track_blocks(pe3)[[n for n, *_ in TS.aggregate_names(pe3)].index('Mono1')], 0x261b)[0], 0x260d)[1])
out = ['# generated by make_send_templates.py — do not edit',
       f"BUS_ENTRY = {{'mono': {flat(by_name['Bus1'])!r}, 'stereo': {flat(by_name['Bus2'])!r}}}",
       f"BUS_NAME = {{'mono': 'Bus1', 'stereo': 'Bus2'}}",
       f"BUS_ID8 = {{'mono': {_id8(by_name['Bus1'])!r}, 'stereo': {_id8(by_name['Bus2'])!r}}}",
       f"REC2602 = {{'mono': {flat(recs['Bus1'])!r}, 'stereo': {flat(recs['Bus2'])!r}}}",
       f"PATHOBJ = {po!r}",
       f"SLOT = {{('mono', 'mono'): {slot_mono_mono!r}, ('mono', 'stereo'): {slot_mono_stereo!r}}}",
       f"E485E_MAIN = {flat(e485[0])!r}",
       f"E485E_SEND = {flat(e485[1])!r}"]
open('ptx_templates_sends.py', 'w').write('\n'.join(out) + '\n')
print('ok')
