#!/usr/bin/env python3
"""make_param_lists.py <session.ptx | список.txt> ... — библиотека записей автоматизируемых параметров плагинов (ptx_templates_params.py).

Запись 0x260f (слот 0x2616 > 0x2614) = имя, номер параметра у хоста AAX, флаги, число шагов, внутренний ID параметра AAX и значение (0x260b).
Pro Tools принимает запись, только если номер и ID настоящие (проверено: имена из page tables вместо ID — список выбрасывается),
поэтому записи берутся из сессий, сохранённых самим Pro Tools. По ним в слот без списка (шаблон без списка, слот по кэшу PT) можно дописать
нужный параметр и записать на него автоматизацию. Ключ — тройка FourCC (mfr, prod, plug): номера у разных форматов каналов разные.
"""
import struct
import sys
import zlib

import ptx_plugins as P
import ptx_trackstate as TS
from ptx_model import PTX
from ptx_to_reaper import flat


def harvest(paths):
    out = {}                                               # тройка -> (число записей, сжатые записи)
    for f in paths:
        try:
            p = PTX(open(f, 'rb').read())
        except Exception:                                  # noqa: BLE001 — битые и чужие файлы пропускаем
            continue
        for ti, tr in enumerate(P.read_plugins(p)):
            for x in tr:
                blk = P._plugin_slot_block(p, ti, x['slot'])
                lst = TS.kids(blk, 0x2614) if blk is not None else []
                ents = TS.kids(lst[0], 0x260f) if lst else []
                key = tuple(x['key'][:3])
                if ents and len(ents) > out.get(key, (0,))[0]:
                    out[key] = (len(ents), zlib.compress(b''.join(flat([e]) for e in ents), 9))
    return out


def main():
    paths = []
    for a in sys.argv[1:]:
        paths += [l.strip() for l in open(a) if l.strip()] if a.endswith('.txt') else [a]
    lib = harvest(paths)
    import os
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ptx_templates_params.py')
    with open(path, 'w') as f:
        f.write('# generated by make_param_lists.py — do not edit\n# (mfr, prod, plug): zlib(записи 0x260f подряд, с заголовками блоков)\nPARAMS = {\n')
        for k, (n, z) in sorted(lib.items()):
            f.write(f'    {k!r}: {z!r},  # {n}\n')
        f.write('}\n')
    print(len(lib), 'plug-ins ->', path, os.path.getsize(path), 'bytes')


if __name__ == '__main__':
    main()
