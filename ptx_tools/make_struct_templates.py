#!/usr/bin/env python3
"""Генерирует ptx_templates_struct.py: блоки дорожек-не-аудио (папка, aux, routing folder) из эталонов Pro Tools.

folder — F1 из lab/oracle9/m_folder.ptx (позиция 1), aux/routing — A1/R1 из lab/oracle9/s_routing.ptx.
Для каждого вида: container (0x263b/0x261e), a251 (0x251a; обе семьи одинаковы), b210 (0x210b), b2589 (0x2589, если есть).
"""
import sys
sys.path.insert(0, '.')
from ptx_model import PTX
import ptx_to_reaper as R, ptx_trackstate as TS

SRC = {'folder': ('lab/oracle9/m_folder.ptx', 'F1'), 'aux': ('lab/oracle9/s_routing.ptx', 'A1'),
       'routing': ('lab/oracle9/s_routing.ptx', 'R1'),
       'audio': ('lab/oracle9/mc_m1.ptx', 'T03'), 'master': ('lab/oracle_master/s1_master.ptx', 'Master 1'), 'audio_st': ('lab/oracle9/mc_m1.ptx', 'S1'), 'audio_51': ('lab/oracle9/mc_m1.ptx', 'M1'), 'video': ('lab/video/v1_start.ptx', '5.1ch-03_MIAbyss_Movie4_MainPV_30s-1st_260728re')}


def blk(b):
    return R.flat([b])


out = ['# generated by make_struct_templates.py — do not edit', 'STRUCT = {']
for kind, (f, name) in SRC.items():
    p = PTX(open(f, 'rb').read())
    ag = TS.aggregate_names(p)
    i = [n for n, *_ in ag].index(name)
    _, a1, a2, end = ag[i]
    assert blk(a1) == blk(a2), 'families differ'
    cont = TS.track_blocks(p)[i]
    b210 = R.kids(R.root(p, 0x2107), 0x210b)[i]
    d = {'container': blk(cont), 'a251': blk(a1), 'b210': blk(b210), 'name': name}
    # id8 и тип из блока 0x251a
    o = TS.own_bytes(a1)
    d['id8'] = o[end + 10:end + 18]
    out.append(f'    {kind!r}: {{')
    for k, v in d.items():
        out.append(f'        {k!r}: {v!r},')
    out.append('    },')
# контейнер папки, созданной в интерфейсе Pro Tools (lab/folder1/f3.ptx): Folder 2 — верхнего уровня, Folder 1 — вложенная
p3 = PTX(open('lab/folder1/f3.ptx', 'rb').read())
ag3 = TS.aggregate_names(p3)
cont3 = TS.track_blocks(p3)
names3 = [n for n, *_ in ag3]
out.append('}')
# полоса микшера (0x2589) папки, 200 байт: из lab/nest/nmin.ptx (первая запись)
pn = PTX(open('lab/nest/nmin.ptx', 'rb').read())
strips = R.kids(R.kids(R.kids(R.kids(R.root(pn, 0x2587), 0x2551)[0], 0x258b)[0], 0x258a)[0], 0x2589)
fs = [blk(b) for b in strips if len(blk(b)) == 200][0]
out.append(f'FOLDER_STRIP = {fs!r}')
out.append('FOLDER_UI = {')
for key, nm in (('top', 'Folder 2'), ('nested', 'Folder 1')):
    i = names3.index(nm)
    _, a1, _, end = ag3[i]
    out.append(f'    {key!r}: {{ "name": {nm!r}, "id8": {TS.own_bytes(a1)[end + 10:end + 18]!r}, "container": {blk(cont3[i])!r} }},')
out.append('}')
# видео (эталон lab/video/v1_start.ptx, сделан Pro Tools: ImportVideo в пустую сессию): дескриптор 0x1005, регион 0x262d, плейлист 0x1053
pv = PTX(open('lab/video/v1_start.ptx', 'rb').read())
r1006, r262e, r1055 = R.root(pv, 0x1006), R.root(pv, 0x262e), R.root(pv, 0x1055)
out.append('VIDEO = {')
out.append(f'    "desc": {blk(R.kids(r1006, 0x1005)[0])!r},')
out.append(f'    "region": {blk(R.kids(r262e, 0x262d)[0])!r},')
out.append(f'    "playlist": {blk(R.kids(r1055, 0x1053)[0])!r},')
pv1 = PTX(open('lab/video/o1_pool1_video.ptx', 'rb').read())                 # полоса микшера (0x2589) видеодорожки, 200 байт; индекс дорожки — байт 9
strips_ = [b for b in R.kids(R.kids(R.kids(R.kids(R.root(pv1, 0x2587), 0x2551)[0], 0x258b)[0], 0x258a)[0], 0x2589) if len(blk(b)) == 200]
out.append(f'    "strip": {blk(strips_[0])!r},')
out.append(f'    "name": "5.1ch-03_MIAbyss_Movie4_MainPV_30s-1st_260728re",')
out.append('}')
open('ptx_templates_struct.py', 'w').write('\n'.join(out) + '\n')
print('ok')
